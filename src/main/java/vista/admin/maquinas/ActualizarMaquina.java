        //ICONOS LtextField
        //Campo nombre de la maquina
        FlatSVGIcon iconoUsuario = new FlatSVGIcon("recursos/iconos/icnEtiqueta.svg", 16, 16);
        txtNombre.putClientProperty("JTextField.leadingIcon", iconoUsuario);
