    //comboboxes
    private void cargarCombosDesdeBD() {
        // --- ESTADOS ---
        DefaultComboBoxModel<String> modelEstados = new DefaultComboBoxModel<>();
        estadoDescToId.clear();

        List<Estado> estados = contr.listarEstado();
        for (Estado e : estados) {
            String desc = e.getDescripcionEstado();
            int id = e.getCodigoEstado();

            modelEstados.addElement(desc);
            estadoDescToId.put(desc, id);
        }
        cbbStatus.setModel(modelEstados);

        // --- TIPOS ---
        DefaultComboBoxModel<String> modelTipos = new DefaultComboBoxModel<>();
        tipoDescToId.clear();

        List<TipoMaquinaria> tipos = contr.listarTipoMaquinaria();
        for (TipoMaquinaria t : tipos) {
            String desc = t.getDescripcionMaq();
            int id = t.getCodigoTipoMaquinaria();

            modelTipos.addElement(desc);
            tipoDescToId.put(desc, id);
        }
        cbbTipo.setModel(modelTipos);
    }

    //cargar máquina seleccionada en la vista anterior
    public void setMaquina(Maquinaria m) {
        this.maquinaActual = m;

        txtNombre.setText(m.getNombre());

        if (m.getFechaAlta() != null) {
            spFechaAlta.setValue(java.sql.Date.valueOf(m.getFechaAlta()));
        }

        if (m.getFechaBaja() != null) {
            spFechaBaja.setValue(java.sql.Date.valueOf(m.getFechaBaja()));
        }

        if (m.getEstado() != null) {
            String estadoDesc = buscarDescPorId(estadoDescToId, m.getEstado().getCodigoEstado());
            if (estadoDesc != null) {
                cbbStatus.setSelectedItem(estadoDesc);
            }
        }

        if (m.getTipoMaquinaria() != null) {
            String tipoDesc = buscarDescPorId(tipoDescToId, m.getTipoMaquinaria().getCodigoTipoMaquinaria());
            if (tipoDesc != null) {
                cbbTipo.setSelectedItem(tipoDesc);
            }
        }

        aplicarReglaFechaBaja();
    }

    private String buscarDescPorId(Map<String, Integer> map, int id) {
        for (Map.Entry<String, Integer> e : map.entrySet()) {
            if (e.getValue() != null && e.getValue() == id) {
                return e.getKey();
            }
        }
        return null;
    }

    //reglas de fechas -> solo va a estar habilitado el spinner de fecha de baja si la máquina está "fuera de servicio"
    private void aplicarReglaFechaBaja() {
        String estado = (String) cbbStatus.getSelectedItem();
        boolean esFuera = estado != null && estado.toLowerCase().contains("fuera");

        spFechaBaja.setEnabled(esFuera);
    }

